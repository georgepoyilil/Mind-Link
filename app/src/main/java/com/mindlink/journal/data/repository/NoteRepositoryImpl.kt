class NoteRepositoryImpl(
    private val context: Context,
    private val database: MindLinkDatabase,
    private val embeddingEngine: EmbeddingEngine,
    private val vectorSearchEngine: VectorSearchEngine,
    private val brainstormingEngine: BrainstormingEngine
) : NoteRepository {

    private val noteDao = database.noteDao()
    private val noteFtsDao = database.noteFtsDao()
    private val embeddingDao = database.embeddingDao()
    private val noteLinkDao = database.noteLinkDao()
    private val synapticGraphEngine = SynapticGraphEngine()
    private val workManager = WorkManager.getInstance(context)

    override fun getAllNotes(): Flow<List<Note>> {
        return noteDao.getAllNotes().map { entities ->
            entities.map { Note.fromEntity(it) }
        }
    }

    override fun getNotesByMood(mood: String): Flow<List<Note>> {
        return noteDao.getNotesByMood(mood).map { entities ->
            entities.map { Note.fromEntity(it) }
        }
    }

    override fun getNoteById(id: Long): Flow<Note?> {
        return noteDao.getNoteById(id).map { entity ->
            entity?.let { Note.fromEntity(it) }
        }
    }

    override suspend fun getNoteByIdSync(id: Long): Note? = withContext(Dispatchers.IO) {
        noteDao.getNoteByIdSync(id)?.let { Note.fromEntity(it) }
    }

    override suspend fun saveNote(note: Note): Long = withContext(Dispatchers.IO) {
        val entity = note.toEntity().copy(
            updatedAt = System.currentTimeMillis()
        )
        val noteId = if (entity.id == 0L) {
            noteDao.insertNote(entity)
        } else {
            noteDao.updateNote(entity)
            entity.id
        }

        // Trigger WorkManager background pipeline asynchronously (does NOT block UI)
        triggerAsyncAiProcessing(noteId)
        rebuildSynapticGraph()

        noteId
    }

    override suspend fun deleteNote(id: Long) = withContext(Dispatchers.IO) {
        noteDao.deleteNoteById(id)
        embeddingDao.deleteByNoteId(id)
        noteLinkDao.deleteLinksForNote(id)
        rebuildSynapticGraph()
    }

    override suspend fun getRelatedThoughts(noteId: Long, topK: Int): List<RelatedThought> = withContext(Dispatchers.IO) {
        val currentEmbedding = embeddingDao.getEmbeddingByNoteId(noteId) ?: run {
            // If embedding not yet generated by worker, compute it dynamically
            val note = noteDao.getNoteByIdSync(noteId) ?: return@withContext emptyList()
            val computed = embeddingEngine.generateEmbedding("${note.title}\n${note.content}")
            computed
        }

        val currentVector = if (currentEmbedding is FloatArray) currentEmbedding else (currentEmbedding as com.mindlink.journal.data.local.entity.NoteEmbeddingEntity).vector
        val allEmbeddings = embeddingDao.getAllEmbeddings()

        val topMatches = vectorSearchEngine.findTopKSimilar(
            queryVector = currentVector,
            candidates = allEmbeddings,
            excludeNoteId = noteId,
            topK = topK,
            threshold = 0.15f
        )

        if (topMatches.isEmpty()) return@withContext emptyList()

        val noteIds = topMatches.map { it.first }
        val notesMap = noteDao.getNotesByIds(noteIds).associateBy { it.id }

        topMatches.mapNotNull { (matchedId, score) ->
            notesMap[matchedId]?.let { entity ->
                RelatedThought(
                    note = Note.fromEntity(entity),
                    similarityScore = score
                )
            }
        }
    }

    override suspend fun searchNotesHybrid(query: String): List<SearchResult> = withContext(Dispatchers.IO) {
        val cleanQuery = query.trim()
        if (cleanQuery.isBlank()) return@withContext emptyList()

        // 1. Keyword search via SQLite FTS with sanitized query
        val ftsExpression = sanitizeFtsQuery(cleanQuery)
        val keywordMatches = if (ftsExpression.isNotBlank()) {
            try {
                noteFtsDao.searchNotesSync(ftsExpression)
            } catch (e: Exception) {
                emptyList()
            }
        } else emptyList()
        val keywordNoteIds = keywordMatches.map { it.id }

        // 2. Vector search via on-device embeddings
        val queryVector = embeddingEngine.generateEmbedding(cleanQuery)
        val allEmbeddings = embeddingDao.getAllEmbeddings()
        val semanticMatches = vectorSearchEngine.findTopKSimilar(
            queryVector = queryVector,
            candidates = allEmbeddings,
            excludeNoteId = null,
            topK = 15,
            threshold = 0.02f
        )

        // 3. Reciprocal Rank Fusion blending
        val blendedRankings = vectorSearchEngine.reciprocalRankFusion(
            keywordRankedIds = keywordNoteIds,
            semanticRankedMatches = semanticMatches
        )

        // 4. Intent & Thematic Expansion
        val lowerQuery = cleanQuery.lowercase(java.util.Locale.ROOT)
        val expandedTokens = mutableSetOf<String>()
        if (lowerQuery.contains("love") || lowerQuery.contains("dating") || lowerQuery.contains("relationship") || lowerQuery.contains("elena") || lowerQuery.contains("partner")) {
            expandedTokens.addAll(listOf("love", "relationship", "elena", "partner", "dating", "presence"))
        }
        if (lowerQuery.contains("fail") || lowerQuery.contains("reject") || lowerQuery.contains("pass") || lowerQuery.contains("setback")) {
            expandedTokens.addAll(listOf("failure", "rejection", "investor", "pass", "setback", "sequoia"))
        }
        if (lowerQuery.contains("family") || lowerQuery.contains("parent") || lowerQuery.contains("dad") || lowerQuery.contains("mom") || lowerQuery.contains("grandpa") || lowerQuery.contains("aging")) {
            expandedTokens.addAll(listOf("family", "parents", "dad", "mom", "grandpa", "aging", "grief"))
        }
        if (lowerQuery.contains("lonel") || lowerQuery.contains("burnout") || lowerQuery.contains("exhaust") || lowerQuery.contains("mental") || lowerQuery.contains("tired")) {
            expandedTokens.addAll(listOf("loneliness", "burnout", "exhaustion", "mental", "pto", "tired"))
        }
        if (lowerQuery.contains("blocker") || lowerQuery.contains("bottleneck") || lowerQuery.contains("issue") || lowerQuery.contains("stuck")) {
            expandedTokens.addAll(listOf("blocker", "bottleneck", "timeout", "latency", "flak"))
        }
        if (lowerQuery.contains("idea") || lowerQuery.contains("startup") || lowerQuery.contains("concept") || lowerQuery.contains("build")) {
            expandedTokens.addAll(listOf("ideas", "hardware", "wearable", "concept"))
        }
        if (lowerQuery.contains("cost") || lowerQuery.contains("money") || lowerQuery.contains("budget") || lowerQuery.contains("cloud")) {
            expandedTokens.addAll(listOf("finance", "cloud", "cost", "aws", "budget"))
        }

        val allIds = (blendedRankings.map { it.first } + keywordNoteIds).distinct()
        val allNotes = if (allIds.isNotEmpty()) noteDao.getNotesByIds(allIds) else (noteDao.getAllNotes().firstOrNull() ?: emptyList())
        if (allNotes.isEmpty()) return@withContext emptyList()

        val notesMap = allNotes.associateBy { it.id }
        val scoreMap = blendedRankings.associate { it.first to it.second }
        val semanticIdSet = semanticMatches.map { it.first }.toSet()
        val keywordIdSet = keywordNoteIds.toSet()

        val rankedResults = allNotes.map { entity ->
            val baseRrfScore = scoreMap[entity.id] ?: 0.01f
            var intentBoost = 0.0f

            if (expandedTokens.isNotEmpty()) {
                val lowerTags = entity.tags.map { it.lowercase(java.util.Locale.ROOT) }
                val lowerTitle = entity.title.lowercase(java.util.Locale.ROOT)
                val lowerContent = entity.content.lowercase(java.util.Locale.ROOT)

                for (token in expandedTokens) {
                    if (lowerTags.any { it == token || it.contains(token) }) intentBoost += 2.0f
                    if (lowerTitle.contains(token)) intentBoost += 1.5f
                    if (lowerContent.contains(token)) intentBoost += 0.4f
                }
            }

            val finalScore = baseRrfScore + intentBoost
            SearchResult(
                note = Note.fromEntity(entity),
                hybridScore = finalScore,
                isSemanticMatch = semanticIdSet.contains(entity.id) || intentBoost > 0f,
                isKeywordMatch = keywordIdSet.contains(entity.id)
            )
        }

        rankedResults
            .sortedByDescending { it.hybridScore }
            .take(15)
    }

    override suspend fun synthesizeSecondBrain(query: String): SynthesisResponse = withContext(Dispatchers.IO) {
        val searchResults = searchNotesHybrid(query)
        val contextNotes = if (searchResults.isNotEmpty()) {
            searchResults.map { it.note }.take(5)
        } else {
            // Graceful fallback: If no direct semantic/keyword hits, provide the latest journal entries
            val all = noteDao.getAllNotes().firstOrNull() ?: emptyList()
            all.take(5).map { Note.fromEntity(it) }
        }

        val synthesisResult = brainstormingEngine.synthesizeNotes(query, contextNotes)

        SynthesisResponse(
            query = query,
            synthesisText = synthesisResult.answer,
            citedNotes = contextNotes,
            keyTakeaways = synthesisResult.keyTakeaways
        )
    }

    private fun sanitizeFtsQuery(query: String): String {
        val stopWords = setOf(
            "what", "is", "the", "have", "i", "a", "an", "in", "on", "to", "for", "of", "my", "me", "do", "does", "did",
            "can", "could", "would", "should", "about", "any", "some", "recently", "noted",
            "how", "why", "when", "where", "who", "which", "are", "am", "was", "were", "been", "being",
            "tell", "show", "feeling", "feel", "feels", "going", "goes", "life", "our", "us", "your", "it", "its", "so", "like"
        )
        val tokens = query.lowercase(java.util.Locale.ROOT)
            .split(Regex("[^a-zA-Z0-9]+"))
            .filter { it.length > 1 && !stopWords.contains(it) }

        if (tokens.isEmpty()) {
            val fallbackTokens = query.split(Regex("[^a-zA-Z0-9]+")).filter { it.isNotBlank() }
            if (fallbackTokens.isEmpty()) return ""
            return fallbackTokens.joinToString(" OR ") { "$it*" }
        }
        return tokens.joinToString(" OR ") { "$it*" }
    }

    override suspend fun reindexAllNotes() = withContext(Dispatchers.IO) {
        val allNotes = noteDao.getAllNotes().firstOrNull() ?: emptyList()
        allNotes.forEach { entity ->
            triggerAsyncAiProcessing(entity.id)
        }
    }

    override fun getNotesCount(): Flow<Int> = noteDao.getNotesCount()

    override fun getEmbeddingsCount(): Flow<Int> = embeddingDao.getEmbeddingsCount()

    override suspend fun rebuildSynapticGraph() = withContext(Dispatchers.IO) {
        val allNotes = noteDao.getAllNotes().firstOrNull() ?: emptyList()
        val computedLinks = synapticGraphEngine.computeSynapticLinks(allNotes)
        noteLinkDao.deleteAllLinks()
        noteLinkDao.insertLinks(computedLinks)
    }

    override fun getSynapseCount(): Flow<Int> = noteLinkDao.getLinkCount()

    override fun getThoughtGraph(): Flow<ThoughtGraph> {
        return combine(noteDao.getAllNotes(), noteLinkDao.getAllLinks()) { notesEntities, linkEntities ->
            val degreeMap = mutableMapOf<Long, Int>()
            linkEntities.forEach { link ->
                degreeMap[link.sourceNoteId] = (degreeMap[link.sourceNoteId] ?: 0) + 1
                degreeMap[link.targetNoteId] = (degreeMap[link.targetNoteId] ?: 0) + 1
            }

            val nodes = notesEntities.map { entity ->
                val note = Note.fromEntity(entity)
                val degree = degreeMap[entity.id] ?: 0
                ThoughtGraphNode(
                    id = entity.id,
                    title = entity.title.ifBlank { "Untitled Thought" },
                    preview = note.previewText,
                    mood = entity.mood,
                    moodEmoji = note.moodEmoji,
                    tags = entity.tags,
                    degree = degree
                )
            }

            val edges = linkEntities.map { link ->
                ThoughtGraphEdge(
                    sourceId = link.sourceNoteId,
                    targetId = link.targetNoteId,
                    linkType = link.linkType,
                    weight = link.weight,
                    label = link.label
                )
            }

            val tagCounts = notesEntities.flatMap { it.tags }
                .filter { it.isNotBlank() }
                .groupingBy { it }
                .eachCount()
                .toList()
                .sortedByDescending { it.second }
                .take(6)

            val clusters = tagCounts.map { (tag, count) ->
                ThoughtGraphCluster(
                    name = "#$tag",
                    nodeCount = count,
                    colorLong = 0xFF818CF8
                )
            }

            ThoughtGraph(nodes = nodes, edges = edges, clusters = clusters)
        }
    }

    private fun triggerAsyncAiProcessing(noteId: Long) {
        val workData = workDataOf(NoteProcessingWorker.KEY_NOTE_ID to noteId)

        val workRequest = OneTimeWorkRequestBuilder<NoteProcessingWorker>()
            .setInputData(workData)
            .addTag(NoteProcessingWorker.WORK_TAG)
            .setBackoffCriteria(
                BackoffPolicy.EXPONENTIAL,
                WorkRequest.MIN_BACKOFF_MILLIS,
                java.util.concurrent.TimeUnit.MILLISECONDS
            )
            .build()

        workManager.enqueueUniqueWork(
            "process_note_$noteId",
            ExistingWorkPolicy.REPLACE,
            workRequest
        )
    }
}
